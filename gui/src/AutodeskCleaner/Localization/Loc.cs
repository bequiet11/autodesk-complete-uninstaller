using System.ComponentModel;

namespace AutodeskCleaner.Localization;

/// <summary>
/// Tiny runtime localization layer. XAML binds through the indexer, so flipping
/// <see cref="Language"/> updates every bound string instantly.
/// </summary>
public sealed class Loc : INotifyPropertyChanged
{
    public static Loc Instance { get; } = new();

    private string _language = "id";

    public event PropertyChangedEventHandler? PropertyChanged;

    public string Language => _language;

    public bool IsEnglish => _language == "en";

    public string this[string key]
    {
        get
        {
            var dict = IsEnglish ? En : Id;
            return dict.TryGetValue(key, out var value) ? value : key;
        }
    }

    public void SetLanguage(string language)
    {
        var normalized = string.Equals(language, "en", StringComparison.OrdinalIgnoreCase) ? "en" : "id";
        if (_language == normalized)
        {
            return;
        }

        _language = normalized;
        PropertyChanged?.Invoke(this, new PropertyChangedEventArgs("Item[]"));
        PropertyChanged?.Invoke(this, new PropertyChangedEventArgs(nameof(Language)));
        PropertyChanged?.Invoke(this, new PropertyChangedEventArgs(nameof(IsEnglish)));
    }

    public string Format(string key, params object?[] args)
    {
        try
        {
            return string.Format(this[key], args);
        }
        catch (FormatException)
        {
            return this[key];
        }
    }

